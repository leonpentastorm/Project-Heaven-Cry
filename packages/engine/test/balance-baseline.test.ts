// @ts-nocheck (a tool run by hand: it asks the engine for its own numbers and writes a table)
// The balance pass, instrument 1 (docs/design/proposals/2026-11-balance-pass.md): the plain attack of each sample weapon
// at four levels of investment against each enemy tier, straight from previewAttack (the same numbers the attack card
// shows). Nothing is simulated yet: this is the yardstick the rest is measured against.
//   BALANCE_OUT=/path/out.md npx vitest run --root packages/engine test/balance-baseline.test.ts
// Without the variable it only checks that the table builds.
import { describe, it, expect } from 'vitest';
import { writeFileSync } from 'node:fs';
import { WEAPON, previewAttack, maxHp } from '../src';
import { fightWith, withGame } from './helpers/perkfight';

const WEAPONS = ['service_pistol', 'frontier_hand_cannon', 'decrkm_smg', 'hellraiser_service_rifle', 'long_rifle', 'coach_gun', 'hellraiser_lmg', 'blackpoint_700', 'breacher_tube', 'recurve_bow', 'crossbow', 'combat_knife', 'sabre', 'maul', 'adamantile_greatsword', 'fists', 'hellraiser_servo_fist'];
/** Investment: the weapon's skill and its attribute, and the level they are legal at (rules 1.13 ceilings). */
const BUILDS = [{ id: 'untrained', pts: 1, level: 1 }, { id: 'start, all in', pts: 7, level: 1 }, { id: 'level 6', pts: 9, level: 6 }, { id: 'level 9+', pts: 10, level: 9 }];
const TIERS = ['minion', 'soldier', 'elite', 'boss'];
const ATTR_OF = { dexterity: 'agility', raw_power: 'strength', athletics: 'strength' };

function measure(weapon: string, b: any, tier: string) {
  const w: any = WEAPON[weapon], skill = w.skill, melee = ['light_melee', 'heavy_melee', 'unarmed'].includes(w.category);
  const f = fightWith([{ weapon, level: b.level, skills: w.category === 'bow' ? { [skill]: b.pts, raw_power: b.pts } : { [skill]: b.pts }, attrs: w.category === 'bow' ? { agility: b.pts, strength: b.pts } : { [ATTR_OF[skill] || 'agility']: b.pts } }], [{ tier, at: 'H6' }]);
  const cb = f.cb, pc = f.pc, foe = f.foe;
  pc.pos = melee ? '6,5' : '3,5'; foe.pos = '7,5'; // next to it, or 4 tiles off on open ground
  const mode = melee ? 'melee' : w.modes?.includes('single') === false ? 'burst' : 'shot';
  const p = withGame(f.g, () => previewAttack(cb, pc, foe, mode));
  if (!p.ok || !p.dmg) return { weapon, build: b.id, tier, why: p.why || 'no damage' };
  const hit = Math.max(0, Math.round(p.dmg.total - Math.max(0, p.dmg.armour - p.dmg.pierce)));
  const critRate = 0.05, ev = (p.pct / 100) * hit * (1 + critRate * (p.dmg.crit - 1));
  return { weapon, cat: w.category, build: b.id, tier, ap: p.ap, pct: p.pct, hit, crit: Math.round(hit * p.dmg.crit), evPerAp: Math.round((ev / Math.max(1, p.ap)) * 10) / 10, toKill: hit > 0 ? Math.ceil(foe.maxHp / hit) : null, foeHp: foe.maxHp, pcHp: pc.maxHp };
}

describe('the balance baseline', () => {
  it('builds the plain-attack table', () => {
    const rows = [];
    for (const w of WEAPONS) for (const b of BUILDS) for (const t of TIERS) rows.push(measure(w, b, t));
    const good = rows.filter((r) => !r.why);
    expect(good.length).toBeGreaterThan(rows.length * 0.8);
    if (process.env.BALANCE_OUT) {
      const L = ['# Balance baseline: the plain attack (generated by packages/engine/test/balance-baseline.test.ts)', '',
        'Open ground, no cover, 4 tiles for guns and bows, next to the target for melee. "Hit" is damage after the tier\'s armour. "Per AP" is hit chance × damage (a 5% critical counted) ÷ AP. "To kill" is hits that land.', ''];
      for (const b of BUILDS) {
        L.push('## ' + b.id + ' (skill and attribute ' + b.pts + ')', '', '| Weapon | AP | ' + TIERS.map((t) => t + ': hit % · dmg · crit · per AP · to kill').join(' | ') + ' |', '|---|---|' + TIERS.map(() => '---').join('|') + '|');
        for (const w of WEAPONS) {
          const rs = TIERS.map((t) => rows.find((r) => r.weapon === w && r.build === b.id && r.tier === t));
          L.push('| ' + w + ' | ' + (rs[0].ap ?? '?') + ' | ' + rs.map((r) => (r.why ? r.why : r.pct + '% · ' + r.hit + ' · ' + r.crit + ' · ' + r.evPerAp + ' · ' + r.toKill)).join(' | ') + ' |');
        }
        L.push('');
      }
      writeFileSync(process.env.BALANCE_OUT, L.join('\n') + '\n');
    }
  });
});
