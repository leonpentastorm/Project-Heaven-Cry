// Rules 1.95 (the scale; docs/design/growth/09-build-order.md step 1, "Proves it"; ruling 50: only what step 1 built).
// Through the reducer (a real combat/attack): the four weapon doors' plain hit (guard, momentum, pressure, shadow: their
// grade is the weapon's, built here) at level 1 by a creation specialist (7 / 7) at Standard and Fine, and at level 20
// (10 / 10) at Relic and Celestial, equal the bible's own reading (tools/balance/check.py --export-scale, filed in
// test/golden/bible-scale.json: the check (a) "plain hit" lines). Character HP at Endurance 1, 4, 7 and 10 and Pain
// Threshold 0, 5 and 10 equals the bible's HP table. The five magic and prayer doors' lines wait for step 5 (their foci
// and Devotion grade, ruling A9). The fixture is regenerated by `python tools/balance/check.py --export-scale`.
import { describe, it, expect, beforeEach } from 'vitest';
import { WEAPON, maxHp } from '../src';
import { physFight, rig } from './helpers/physfight';
import bible from './golden/bible-scale.json';

beforeEach(() => rig(null));
const B: any = bible;
const WEAPON_DOORS = ['guard', 'momentum', 'pressure', 'shadow'];

/** The plain hit a character with `pts` in its weapon's own pair (the row's scales_with and hits_with) deals at `level`
 * with the weapon at `grade`, through the reducer, on a foe of its level with no armour. */
function plainHit(weapon: string, level: number, pts: number, grade: string): number {
  const ph: any = (WEAPON[weapon] as any).phys, attrs: Record<string, number> = {}, skills: Record<string, number> = {};
  for (const a of ph.scales_with) attrs[a] = pts;
  for (const s of ph.also_scales?.length ? ph.also_scales : [ph.hits_with]) skills[s] = pts;
  const f = physFight([{ weapon, level, attrs, skills, known: [], grade: { main: grade } }], [{ tier: 'soldier', level, weapon: 'service_pistol' }]);
  f.cb.objects = [];
  const melee = ph.system === 'melee';
  f.put(f.pc, 'C5'); const foe = f.put(f.foe, melee ? 'D5' : 'J5');
  foe.hp = foe.maxHp = 10_000_000; foe.armour = 0;
  f.turn(f.pc); rig({ hit: true, die: 12 });
  const before = f.unit(f.foe.id).hp;
  f.act({ type: 'combat/attack', unitId: f.pc.id, targetId: f.foe.id, mode: melee ? 'melee' : 'shot' } as any);
  return before - f.unit(f.foe.id).hp;
}

describe('rules 1.95, step 1: the weapon doors\' plain hit equals the bible (check (a))', () => {
  for (const id of WEAPON_DOORS) {
    const d = B.doors[id];
    it(`${id} (${d.weapon}): level 1 at Standard and Fine, level 20 at Relic and Celestial`, () => {
      for (const [g, v] of Object.entries(d.l1) as [string, number][]) expect(plainHit(d.weapon, 1, d.l1_points, g)).toBe(Math.floor(v));
      for (const [g, v] of Object.entries(d.l20) as [string, number][]) expect(plainHit(d.weapon, 20, 10, g)).toBe(Math.floor(v));
    });
  }
  it('a level-1 plain hit is one or two digits, a level-20 one four (the scale as Leon ruled it)', () => {
    for (const id of WEAPON_DOORS) {
      const d = B.doors[id];
      for (const v of Object.values(d.l1) as number[]) expect(Math.floor(v)).toBeLessThan(100);
      for (const v of Object.values(d.l20) as number[]) { expect(Math.floor(v)).toBeGreaterThanOrEqual(1000); expect(Math.floor(v)).toBeLessThan(10000); }
    }
  });
});

describe('rules 1.95, step 1: character HP equals the bible\'s table', () => {
  it('Endurance 1, 4, 7, 10 with Pain Threshold 0, 5, 10, at levels 1, 5, 10, 15 and 20', () => {
    for (const r of B.hp as { level: number; endurance: number; pain_threshold: number; hp: number }[]) {
      const f = physFight([{ level: r.level, attrs: { endurance: r.endurance }, skills: { pain_threshold: r.pain_threshold }, perks: [], traits: [] }], [{}]);
      const c = f.char(f.pc);
      expect(maxHp(c)).toBe(r.hp);
    }
  });
});
