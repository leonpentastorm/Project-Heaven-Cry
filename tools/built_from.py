#!/usr/bin/env python3
"""A lone session's self-check: is this built FROM the engine, or BESIDE it?

    npm run built-from -- docs/design/my-spec.md     a design spec: its "Built from" and "Needs a new primitive" sections
    npm run built-from -- develop..HEAD              a git range: the smells of building beside the engine in its diff
    npm run built-from                               the working tree against HEAD
    npm run built-from -- --diff-file some.diff      a diff saved in a file (the tests use this)

On a spec: every name in backticks in the "Built from" section is looked up in docs/ENGINE-HOOKS.md (the catalogue,
generated by tools/engine_catalog.py), in data/*.json (ids, fields) and in the repo's paths. A name found nowhere is a
typo, an invented hook, or a genuinely new primitive, which must then be listed under "Needs a new primitive" (and is
first checked against docs/design/rev4-primitives.md). A name under "Needs a new primitive" that the catalogue already
has is reported too: it exists. The check FAILS (exit 1) when the spec has no "Built from" table.

On a diff: the added lines are read for the smells in packages/engine/test/lint-patterns.json (the same patterns the
lint tests use) and a few that need the diff itself (a new lane file, a new field that counts). Each smell prints the
file, the line and the primitive to use instead, from the catalogue. Advisory (exit 0) except where a lint already
fails: a 'zero' pattern, or a 'ratchet' pattern a file gains more of than it lost.
"""
import json, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import engine_catalog as EC  # noqa: E402

ROOT = EC.ROOT
CATALOG = 'docs/ENGINE-HOOKS.md'
PATTERNS = 'packages/engine/test/lint-patterns.json'
LANE_DIRS = ('packages/engine/src/perks/', 'packages/engine/src/classes/', 'packages/engine/src/calls/')


# ------------------------------------------------------------------------------------------------ what is known
def catalogue():
    """(names, points, entries). names: every single code name the catalogue writes in backticks (a table's name,
    a field, a scope; not the insides of a signature). points: the names that ARE extension points (a trigger,
    predicate, op, hook, stat, export...: the first column of a table, fx kinds and guards left out). entries: name ->
    (file, signature, what for) for the primitives' exports."""
    path = os.path.join(ROOT, CATALOG)
    if not os.path.exists(path): sys.exit('built_from: ' + CATALOG + ' is missing: run python3 tools/engine_catalog.py')
    text = open(path, encoding='utf-8').read()
    names, points, entries, file_, h3 = set(), set(), {}, '', ''
    for line in text.split('\n'):
        if line.startswith('## ') or line.startswith('### '): h3 = line; file_ = ''
        h = re.match(r'#### .*\(`([^`]+)`\)\s*$', line)
        if h: file_ = h.group(1); continue
        row = re.match(r'\| `([^`]+)` \| `((?:[^`]|``)*)` \| (.*) \|$', line)
        if row and file_: entries.setdefault(row.group(1), (file_, row.group(2), row.group(3)))
        first = re.match(r'\| `([^`]+)` \|', line)
        if first and not re.search(r'Fx event kinds|`costs`|guards|Resources|Output profiles', h3): points.add(first.group(1).rstrip('<…>'))
        for span in re.findall(r'`([^`]+)`', line):
            sp = span.strip().rstrip('<…>')
            if re.fullmatch(r'[A-Za-z_][\w]*(?:[.:][A-Za-z_][\w]*)*:?', sp): names.add(sp)
    return names | points, points, entries


VALUE_KEYS = {'id', 'op', 'when', 'stat', 'condition', 'action', 'site', 'resource', 'kind', 'type', 'scope', 'uses', 'target', 'word', 'family', 'profile', 'per', 'of', 'hook', 'trigger'}


def data_names():
    """Every id and every field name in data/*.json, and the values of the fields that name things (op, when, stat...)."""
    ids, keys = set(), set()

    def walk(x):
        if isinstance(x, dict):
            for k, v in x.items():
                keys.add(k)
                if k in VALUE_KEYS and isinstance(v, str) and re.fullmatch(r'[a-z][\w]*(?:[.:][\w]+)*', v): ids.add(v)
                walk(v)
        elif isinstance(x, list):
            for v in x: walk(v)
    for d, _, fs in os.walk(os.path.join(ROOT, 'data')):
        for f in fs:
            if f.endswith('.json'):
                try: walk(json.load(open(os.path.join(d, f), encoding='utf-8')))
                except Exception: pass
    return ids | keys


def engine_names():
    """name -> file for every function, const, class, interface and type the engine and the client declare (exported or
    not), and every field of an interface: a name that exists in the code but is not a catalogued extension point."""
    out = {}
    for base in (EC.SRC, 'apps/web/src'):
        for rel in EC.ts_files(base):
            code = EC.blank_comments(EC.read(rel))
            for m in re.finditer(r'\b(?:function|const|let|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)', code): out.setdefault(m.group(1), EC.short(rel))
            for m in re.finditer(r'^\s+(?:readonly\s+)?([A-Za-z_]\w*)\??:\s', code, re.M): out.setdefault(m.group(1), EC.short(rel))
            for m in re.finditer(r"(?:^|[\s{,])'?([a-z_][\w]*)'?\s*:\s*[\('{\[]", code): out.setdefault(m.group(1), EC.short(rel))
    return out


_FILES = []


def path_exists(p):
    """Is this a file of the repo: from the root, from a usual base, or as the end of any tracked path?"""
    p = p.strip().rstrip('/')
    for base in ('', EC.SRC + '/', 'data/', 'docs/design/', 'docs/', 'apps/web/src/', 'packages/engine/'):
        if os.path.exists(os.path.join(ROOT, base + p)): return True
    if not _FILES:
        r = subprocess.run(['git', 'ls-files'], cwd=ROOT, capture_output=True, text=True)
        _FILES.extend(r.stdout.split('\n'))
    return any(f == p or f.endswith('/' + p) for f in _FILES)


IDENT = re.compile(r'[A-Za-z_][\w]*(?:[.:][A-Za-z_][\w]*)*:?')


def idents(span):
    """The code names in a backticked span: paths and quoted strings taken out, dotted and prefixed names kept whole."""
    span = re.sub(r'"[^"]*"|\'[^\']*\'', ' ', span)
    span = re.sub(r'\S+\.(?:ts|tsx|js|json|md|py)\b', ' ', span)
    return [t for t in IDENT.findall(span) if len(t.strip(':')) > 1]


class Known:
    def __init__(self):
        self.cat, self.points, self.entries = catalogue()
        self.data = data_names()
        self.engine = engine_names()

    def where(self, t):
        """'catalogue', 'data', 'engine:<file>' or None for one name."""
        bare = t.rstrip(':')
        parts = [bare] + re.split(r'[.:]', bare)
        if bare in self.cat or (t.endswith(':') and t in self.cat) or any(p + ':' in self.cat for p in parts[:1]): return 'catalogue'
        if bare.split(':')[0] + ':' in self.cat: return 'catalogue'
        if bare in self.data: return 'data'
        last = re.split(r'[.:]', bare)[-1]
        if '.' in bare and (last in self.cat): return 'catalogue'
        if '.' in bare and last in self.data: return 'data'
        if bare in self.engine: return 'engine:' + self.engine[bare]
        if '.' in bare and last in self.engine: return 'engine:' + self.engine[last]
        return None


# ------------------------------------------------------------------------------------------------ spec mode
MARK = re.compile(r'(?:^#+\s.*?|\*\*)(Built from|Needs a new primitive)', re.I)


def sections(lines):
    """{'built': [(line no, text)], 'needs': [...]} and whether the Built-from section holds a table."""
    out = {'built': [], 'needs': []}; cur = None; table = False; cur_level = 9
    for i, l in enumerate(lines, 1):
        h = re.match(r'(#+)\s', l)
        pieces = []
        # a marker may sit inside a paragraph ("**Built from:** … **Needs a new primitive:** …"): split at each one
        idx = [(m.start(), m.group(1).lower()) for m in MARK.finditer(l) if not (l.lstrip().startswith('|'))]
        if h and not idx and cur and len(h.group(1)) <= cur_level: cur = None
        if not idx:
            if cur and re.match(r'\*\*[^*]+\*\*', l.strip()) and not l.strip().startswith('**new'): cur = None  # the next bold label ends it
            if cur: out[cur].append((i, l)); table = table or (cur == 'built' and l.lstrip().startswith('|'))
            continue
        pos = 0
        if cur and idx[0][0] > 0: out[cur].append((i, l[:idx[0][0]]))
        for k, (p, name) in enumerate(idx):
            cur = 'built' if name.startswith('built') else 'needs'
            cur_level = len(h.group(1)) if h else 9
            end = idx[k + 1][0] if k + 1 < len(idx) else len(l)
            out[cur].append((i, l[p:end]))
    return out, table


def check_spec(path, K):
    lines = open(os.path.join(ROOT, path) if not os.path.isabs(path) else path, encoding='utf-8').read().split('\n')
    sec, table = sections(lines)
    print(path)
    if not sec['built']:
        print('  FAIL: no "Built from" section. Every design spec has one: a table, each rule against the primitive that carries it (docs/ENGINE-HOOKS.md).')
        return 1, {'unknown': None}
    declared = set()
    for _, l in sec['needs']:
        for span in re.findall(r'`([^`]+)`', l): declared |= {t.rstrip(':') for t in idents(span)}
    seen, unknown, engine_only, counts = set(), [], [], {'catalogue': 0, 'data': 0, 'engine': 0, 'path': 0, 'new': 0}
    for no, l in sec['built']:
        for m in re.finditer(r'`([^`]+)`', l):
            span = m.group(1)
            for piece in re.findall(r'\S+\.(?:ts|tsx|js|json|md|py)\b', span):
                counts['path'] += 1
                if not path_exists(piece): unknown.append((no, piece, 'no such file'))
            new_here = bool(re.search(r'\bnew\W{0,6}$', l[:m.start()]))
            for t in idents(span):
                key = t.rstrip(':')
                if key in seen: continue
                seen.add(key)
                w = K.where(t)
                if w == 'catalogue': counts['catalogue'] += 1
                elif w == 'data': counts['data'] += 1
                elif w: counts['engine'] += 1; engine_only.append((no, key, w[7:]))
                elif new_here or key in declared: counts['new'] += 1
                else: unknown.append((no, key, ''))
    exists = []
    for no, l in sec['needs']:
        for span in re.findall(r'`([^`]+)`', l):
            for t in idents(span):
                k = t.rstrip(':')
                if k in K.points and k not in [e[1] for e in exists]: exists.append((no, k))
    n = sum(counts.values())
    print(f'  Built from: {"a table" if table else "NO TABLE"}; {n} names: {counts["catalogue"]} in the catalogue, {counts["data"]} in data, '
          f'{counts["path"]} paths, {counts["engine"]} in the engine but not catalogued, {counts["new"]} marked new or listed under "Needs a new primitive", {len(unknown)} unknown')
    if unknown:
        print('  Unknown (not in the catalogue, data or engine, and not listed as new: a typo, an invention, or a primitive to list under "Needs a new primitive"):')
        for no, t, why in unknown: print(f'    line {no}: `{t}`' + (f' ({why})' if why else ''))
    if engine_only:
        print('  In the engine but not a catalogued extension point (is it the door, or a private helper?):')
        print('    ' + ', '.join(f'`{t}` ({f})' for _, t, f in engine_only))
    if sec['needs']:
        print(f'  Needs a new primitive: {len(declared)} names' + (f'; already extension points in the catalogue (check the ask is not one of them): ' + ', '.join(f'`{t}` (line {no})' for no, t in exists) if exists else ''))
        print('  Before building any: read docs/design/rev4-primitives.md (26 asked, 12 needed on 13 Nov 2026) and fold into what is there.')
    if not table:
        print('  FAIL: the "Built from" section has no table (| rule | primitive | where |).')
        return 1, {'unknown': len(unknown)}
    print('  ok')
    return 0, {'unknown': len(unknown)}


# ------------------------------------------------------------------------------------------------ diff mode
def parse_diff(text):
    """[(path, added: [(line, text)], removed: [(line, text)], new_file: bool)]."""
    files, cur = [], None
    old_no = new_no = 0
    for l in text.split('\n'):
        if l.startswith('diff --git'):
            cur = {'path': None, 'added': [], 'removed': [], 'new': False}; files.append(cur); continue
        if cur is None:
            cur = {'path': None, 'added': [], 'removed': [], 'new': False}; files.append(cur)
        if l.startswith('new file mode') or l.startswith('--- /dev/null'): cur['new'] = True; continue
        if l.startswith('+++ '):
            p = l[4:].strip(); cur['path'] = p[2:] if p.startswith('b/') else p; continue
        if l.startswith('--- '): continue
        h = re.match(r'@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@', l)
        if h: old_no, new_no = int(h.group(1)), int(h.group(2)); continue
        if l.startswith('+'): cur['added'].append((new_no, l[1:])); new_no += 1
        elif l.startswith('-'): cur['removed'].append((old_no, l[1:])); old_no += 1
        elif l.startswith(' '): old_no += 1; new_no += 1
    return [f for f in files if f['path'] and f['path'] != '/dev/null']


def code_of(line):
    """A line with its comment and string contents taken out (a smell in prose is not a smell)."""
    s = line.strip()
    if s.startswith(('//', '*', '/*')): return ''
    s = re.sub(r"(?<![:'\"`\\])//.*$", '', line)
    return re.sub(r'/\*.*?\*/', '', s)


def instead(names, K):
    out = []
    for n in names:
        e = K.entries.get(n)
        out.append(f'`{n}` ({e[0]})' if e else f'`{n}`')
    return ', '.join(out)


def check_diff(text, K):
    P = json.load(open(os.path.join(ROOT, PATTERNS), encoding='utf-8'))['patterns']
    files = parse_diff(text)
    smells, fails = [], 0
    unit_fields = {f['name'] for f in EC.interface_fields(EC.read(EC.SRC + '/combat.ts'), re.search(r'^export interface Unit\b', EC.read(EC.SRC + '/combat.ts'), re.M).start())}
    combat_fields = {f['name'] for f in EC.interface_fields(EC.read(EC.SRC + '/combat.ts'), re.search(r'^export interface Combat\b', EC.read(EC.SRC + '/combat.ts'), re.M).start())}
    item_ids = K.data

    touched = {f['path'] for f in files}

    def add(path, no, why, use, lint=None, hard=False):
        smells.append((path, no, why, use, lint, hard))

    for f in files:
        path = f['path']
        if f['new'] and path.startswith(LANE_DIRS) and path.endswith('.ts'):
            add(path, 1, 'a new lane file (perks/, classes/, calls/): a new item is data, a new behaviour a general primitive',
                instead(['runTriggered', 'registerActions'], K) + '; docs/ENGINE-GUIDE.md "Stop: before you build"')
        rel_engine = path[len(EC.SRC) + 1:] if path.startswith(EC.SRC + '/') else path
        for pid, p in P.items():
            if not re.search(p['scope'], path): continue
            if any((re.search(s, path) if any(c in s for c in '\\$^(') else rel_engine == s) for s in p.get('skip', [])): continue
            rx = re.compile(p['re'])
            gained = []
            for no, line in f['added']:
                c = code_of(line)
                if pid == 'register_block': c = line  # the lint reads a register block from its first column
                for m in rx.finditer(c):
                    if pid == 'ap_write' and m.group(1) in p.get('not_a_unit', []): continue
                    if pid == 'handler_literal' and m.group(1) in p.get('ignore_values', []): continue
                    if pid == 'item_case':
                        iid = m.group(1) or m.group(2)
                        if not (path.startswith(LANE_DIRS) or iid in item_ids or '_' in iid or '.' in iid or ':' in iid): continue
                    if pid == 'counter_field' and (m.group(1) in unit_fields or m.group(1) in combat_fields): continue
                    gained.append(no); break
            if not gained: continue
            lost = 0
            if p['kind'] == 'ratchet':
                lost = sum(1 for _, line in f['removed'] if rx.search(code_of(line) if pid != 'register_block' else line))
            hard = p['kind'] == 'zero' or (p['kind'] == 'ratchet' and len(gained) > lost)
            why = p['why']
            if hard and p['kind'] == 'ratchet' and p.get('lint') and 'packages/engine/test/' + p['lint'] in touched:
                hard = False; why += ' (the lint\'s own table is changed in this diff: was it raised on purpose?)'
            for no in gained:
                add(path, no, why, instead(p['instead'], K), p.get('lint'), hard)
        # a new field on Unit or Combat that counts (combat.ts interfaces)
        if path == EC.SRC + '/combat.ts':
            for no, line in f['added']:
                m = re.match(r'\s*(?:/\*\*.*?\*/\s*)?(\w+)\??:\s', line)
                if m and m.group(1) not in unit_fields | combat_fields and re.search(r'(Round|Turn|Used|Uses|Count|Cool|Cd|Last|Times|Spent)$', m.group(1)):
                    add(path, no, 'a new field on Unit or Combat that counts uses, rounds or a cooldown', instead(['uses'], K))
    groups = {}
    for path, no, why, use, lint, hard in smells:
        g = groups.setdefault((path, why), {'lines': [], 'use': use, 'lint': lint, 'hard': False})
        g['lines'].append(no); g['hard'] = g['hard'] or hard
    for (path, why), g in groups.items():
        fails += g['hard']
        ls = g['lines']; at = str(ls[0]) + (' (also lines ' + ', '.join(map(str, ls[1:8])) + (' …' if len(ls) > 8 else '') + ')' if len(ls) > 1 else '')
        print(f'{path}:{at}: {"FAIL" if g["hard"] else "smell"}: {why}.\n    use instead: {g["use"]}' + (f'  [lint: packages/engine/test/{g["lint"]}]' if g['lint'] else ''))
    print(f'{len(smells)} smells in {len(groups)} places, {fails} that a lint fails on' if smells else 'no smells: nothing built beside the engine in this diff')
    print('Then: npm run check.')
    return 1 if fails else 0


def main():
    args = sys.argv[1:]
    K = Known()
    if '--diff-file' in args:
        p = args[args.index('--diff-file') + 1]
        return check_diff(open(p, encoding='utf-8').read(), K)
    specs = [a for a in args if a.endswith('.md')]
    if specs:
        rc = 0
        for s in specs: rc |= check_spec(s, K)[0]; print()
        return rc
    rng = args[0] if args else 'HEAD'
    diff = subprocess.run(['git', 'diff', '--unified=0', rng], cwd=ROOT, capture_output=True, text=True)
    if diff.returncode: sys.exit('built_from: git diff ' + rng + ' failed: ' + diff.stderr.strip())
    return check_diff(diff.stdout, K)


if __name__ == '__main__':
    sys.exit(main())
